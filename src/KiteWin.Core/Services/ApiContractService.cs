using System.Text;

namespace KiteWin.Core.Services;

public enum ApiHttpMethod
{
    Get,
    Post,
    Put,
    Delete
}

public record ApiRoute(
    string Path,
    ApiHttpMethod Method,
    string Summary,
    string? RequestBodySample,
    string ResponseBodySample
);

public static class ApiContractBuilder
{
    public static IReadOnlyList<ApiRoute> StarterPack => new[]
    {
        new ApiRoute(
            "/api/projects",
            ApiHttpMethod.Get,
            "Список всех проектов пользователя",
            null,
            """
            [
              { "id": "proj_1", "title": "Kite Studio", "status": "active", "updatedAt": "2026-11-06T12:00:00Z" }
            ]
            """
        ),
        new ApiRoute(
            "/api/projects",
            ApiHttpMethod.Post,
            "Создание нового проекта",
            """
            { "title": "Новый проект", "platform": "Web" }
            """,
            """
            { "id": "proj_new", "title": "Новый проект", "status": "active", "createdAt": "2026-11-06T18:00:00Z" }
            """
        )
    };

    public static string GenerateTypeScriptClient(IReadOnlyList<ApiRoute> routes)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// api/client.ts");
        sb.AppendLine("// Strictly typed API Client generated by KiteWin");
        sb.AppendLine();
        sb.AppendLine("const BASE_URL = process.env.NEXT_PUBLIC_API_URL || '';");
        sb.AppendLine();
        sb.AppendLine("async function request<T>(path: string, options?: RequestInit): Promise<T> {");
        sb.AppendLine("  const res = await fetch(`${BASE_URL}${path}`, {");
        sb.AppendLine("    ...options,");
        sb.AppendLine("    headers: {");
        sb.AppendLine("      'Content-Type': 'application/json',");
        sb.AppendLine("      ...options?.headers,");
        sb.AppendLine("    },");
        sb.AppendLine("  });");
        sb.AppendLine("  if (!res.ok) {");
        sb.AppendLine("    throw new Error(`API Error ${res.status}: ${res.statusText}`);");
        sb.AppendLine("  }");
        sb.AppendLine("  return res.json();");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export const api = {");

        foreach (var r in routes)
        {
            var methodName = r.Method.ToString().ToLowerInvariant();
            var sanitizedPath = r.Path.Replace("/", "_").Trim('_');
            var funcName = $"{methodName}_{sanitizedPath}";

            if (r.Method == ApiHttpMethod.Get)
            {
                sb.AppendLine($"  // {r.Summary}");
                sb.AppendLine($"  {funcName}: async () => request<any>('{r.Path}', {{ method: 'GET' }}),");
            }
            else
            {
                sb.AppendLine($"  // {r.Summary}");
                sb.AppendLine($"  {funcName}: async (data: any) => request<any>('{r.Path}', {{");
                sb.AppendLine($"    method: '{r.Method.ToString().ToUpperInvariant()}',");
                sb.AppendLine("    body: JSON.stringify(data),");
                sb.AppendLine("  }),");
            }
        }

        sb.AppendLine("};");
        return sb.ToString();
    }

    public static string GenerateMarkdownContract(string title, IReadOnlyList<ApiRoute> routes)
    {
        var cleanTitle = string.IsNullOrWhiteSpace(title) ? "Project" : title.Trim();
        var sb = new StringBuilder();
        sb.AppendLine($"# API CONTRACT & HTTP PLAYGROUND: {cleanTitle.ToUpperInvariant()}");
        sb.AppendLine("Verified endpoints and payload schemas for Antigravity Vibe-Coding.");
        sb.AppendLine();

        foreach (var r in routes)
        {
            sb.AppendLine($"### `{r.Method.ToString().ToUpperInvariant()} {r.Path}`");
            sb.AppendLine($"**Описание**: {r.Summary}");
            sb.AppendLine();

            if (!string.IsNullOrWhiteSpace(r.RequestBodySample))
            {
                sb.AppendLine("**Request Body (JSON)**:");
                sb.AppendLine("```json");
                sb.AppendLine(r.RequestBodySample.Trim());
                sb.AppendLine("```");
                sb.AppendLine();
            }

            sb.AppendLine("**Response Body (JSON)**:");
            sb.AppendLine("```json");
            sb.AppendLine(r.ResponseBodySample.Trim());
            sb.AppendLine("```");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    public static string GenerateCurlSnippets(IReadOnlyList<ApiRoute> routes)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Interactive cURL snippets");
        sb.AppendLine();

        foreach (var r in routes)
        {
            sb.AppendLine($"# {r.Summary}");
            if (r.Method == ApiHttpMethod.Get)
            {
                sb.AppendLine($"curl -s -X GET \"http://localhost:3000{r.Path}\" \\");
                sb.AppendLine("  -H \"Accept: application/json\"");
            }
            else
            {
                var body = r.RequestBodySample?.Replace("\"", "\\\"").Replace("\n", " ") ?? "{}";
                sb.AppendLine($"curl -s -X {r.Method.ToString().ToUpperInvariant()} \"http://localhost:3000{r.Path}\" \\");
                sb.AppendLine("  -H \"Content-Type: application/json\" \\");
                sb.AppendLine($"  -d \"{body}\"");
            }
            sb.AppendLine();
        }

        return sb.ToString();
    }
}
