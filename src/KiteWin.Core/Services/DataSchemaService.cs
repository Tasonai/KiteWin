using System.Text;

namespace KiteWin.Core.Services;

public enum FieldDataType
{
    Uuid,
    String,
    Integer,
    Boolean,
    DateTime,
    Json
}

public record SchemaField(
    string Name,
    FieldDataType Type,
    bool IsPrimaryKey = false,
    bool IsOptional = false,
    bool IsIndexed = false
);

public record SchemaEntity(
    string Name,
    IReadOnlyList<SchemaField> Fields
);

public static class DataSchemaDesigner
{
    public static IReadOnlyList<SchemaEntity> StarterPack => new[]
    {
        new SchemaEntity("User", new[]
        {
            new SchemaField("id", FieldDataType.Uuid, IsPrimaryKey: true),
            new SchemaField("email", FieldDataType.String, IsIndexed: true),
            new SchemaField("name", FieldDataType.String, IsOptional: true),
            new SchemaField("role", FieldDataType.String, IsIndexed: true),
            new SchemaField("created_at", FieldDataType.DateTime, IsIndexed: true)
        }),
        new SchemaEntity("Project", new[]
        {
            new SchemaField("id", FieldDataType.Uuid, IsPrimaryKey: true),
            new SchemaField("tenant_id", FieldDataType.Uuid, IsIndexed: true),
            new SchemaField("title", FieldDataType.String),
            new SchemaField("status", FieldDataType.String, IsIndexed: true),
            new SchemaField("created_at", FieldDataType.DateTime, IsIndexed: true),
            new SchemaField("updated_at", FieldDataType.DateTime)
        })
    };

    public static string GeneratePostgreSqlDdl(IReadOnlyList<SchemaEntity> entities)
    {
        var sb = new StringBuilder();
        sb.AppendLine("-- PostgreSQL Production DDL Schema");
        sb.AppendLine("-- Generated by KiteWin Architecture Studio");
        sb.AppendLine("CREATE EXTENSION IF NOT EXISTS \"uuid-ossp\";");
        sb.AppendLine();

        foreach (var entity in entities)
        {
            var tableName = entity.Name.ToLowerInvariant() + "s";
            sb.AppendLine($"CREATE TABLE IF NOT EXISTS {tableName} (");
            for (var i = 0; i < entity.Fields.Count; i++)
            {
                var f = entity.Fields[i];
                var colType = f.Type switch
                {
                    FieldDataType.Uuid => "UUID",
                    FieldDataType.String => "VARCHAR(255)",
                    FieldDataType.Integer => "INTEGER",
                    FieldDataType.Boolean => "BOOLEAN",
                    FieldDataType.DateTime => "TIMESTAMPTZ",
                    FieldDataType.Json => "JSONB",
                    _ => "TEXT"
                };

                var constraints = new List<string>();
                if (f.IsPrimaryKey) constraints.Add("PRIMARY KEY DEFAULT uuid_generate_v4()");
                if (!f.IsOptional && !f.IsPrimaryKey) constraints.Add("NOT NULL");
                if (f.Type == FieldDataType.DateTime && f.Name.Contains("created")) constraints.Add("DEFAULT NOW()");

                var constraintStr = constraints.Count > 0 ? " " + string.Join(" ", constraints) : "";
                var comma = (i < entity.Fields.Count - 1) ? "," : "";
                sb.AppendLine($"  {f.Name.ToLowerInvariant()} {colType}{constraintStr}{comma}");
            }
            sb.AppendLine(");");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    public static string GeneratePrismaSchema(IReadOnlyList<SchemaEntity> entities)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// prisma/schema.prisma");
        sb.AppendLine("datasource db {");
        sb.AppendLine("  provider = \"postgresql\"");
        sb.AppendLine("  url      = env(\"DATABASE_URL\")");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("generator client {");
        sb.AppendLine("  provider = \"prisma-client-js\"");
        sb.AppendLine("}");
        sb.AppendLine();

        foreach (var entity in entities)
        {
            sb.AppendLine($"model {entity.Name} {{");
            foreach (var f in entity.Fields)
            {
                var pType = f.Type switch
                {
                    FieldDataType.Uuid => "String",
                    FieldDataType.String => "String",
                    FieldDataType.Integer => "Int",
                    FieldDataType.Boolean => "Boolean",
                    FieldDataType.DateTime => "DateTime",
                    FieldDataType.Json => "Json",
                    _ => "String"
                };

                var opt = f.IsOptional ? "?" : "";
                var attrs = new List<string>();
                if (f.IsPrimaryKey) attrs.Add("@id @default(uuid())");
                if (f.Name == "email") attrs.Add("@unique");
                if (f.Type == FieldDataType.DateTime && f.Name.Contains("created")) attrs.Add("@default(now())");
                if (f.Type == FieldDataType.DateTime && f.Name.Contains("updated")) attrs.Add("@updatedAt");

                var attrStr = attrs.Count > 0 ? " " + string.Join(" ", attrs) : "";
                sb.AppendLine($"  {f.Name} {pType}{opt}{attrStr}");
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    public static string GenerateCompositeIndexes(string title, IReadOnlyList<SchemaEntity> entities)
    {
        var cleanTitle = string.IsNullOrWhiteSpace(title) ? "Project" : title.Trim();
        var sb = new StringBuilder();
        sb.AppendLine($"# DATABASE INDEXING & QUERY PLAN SPEC: {cleanTitle.ToUpperInvariant()}");
        sb.AppendLine("Mandatory high-performance B-Tree and GIN indexes to prevent Full Table Scans.");
        sb.AppendLine();
        sb.AppendLine("```sql");

        foreach (var entity in entities)
        {
            var tableName = entity.Name.ToLowerInvariant() + "s";
            var indexedFields = entity.Fields.Where(f => f.IsIndexed && !f.IsPrimaryKey).ToList();
            if (indexedFields.Count > 0)
            {
                var cols = string.Join(", ", indexedFields.Select(f => f.Name.ToLowerInvariant()));
                sb.AppendLine($"-- High throughput composite index for {tableName} queries");
                sb.AppendLine($"CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_{tableName}_lookup");
                sb.AppendLine($"  ON {tableName} ({cols});");
                sb.AppendLine();
            }
        }

        sb.AppendLine("```");
        sb.AppendLine("## Antigravity Database Directives:");
        sb.AppendLine("1. Never query large tables without matching composite index columns.");
        sb.AppendLine("2. Always use CONCURRENTLY in production migrations to avoid locking write traffic.");
        sb.AppendLine("3. Keep foreign key columns indexed to ensure fast CASCADE operations.");

        return sb.ToString();
    }
}
