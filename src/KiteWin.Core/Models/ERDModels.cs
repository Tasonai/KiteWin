using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json.Serialization;

namespace KiteWin.Core.Models;

public sealed class ERDColumn
{
    [JsonPropertyName("name")]
    public string Name { get; set; } = "";

    [JsonPropertyName("type")]
    public string Type { get; set; } = "VARCHAR(255)";

    [JsonPropertyName("isPrimaryKey")]
    public bool IsPrimaryKey { get; set; }

    [JsonPropertyName("isNullable")]
    public bool IsNullable { get; set; }

    [JsonPropertyName("isForeignKey")]
    public bool IsForeignKey { get; set; }

    [JsonPropertyName("referencesTable")]
    public string? ReferencesTable { get; set; }

    [JsonPropertyName("referencesColumn")]
    public string? ReferencesColumn { get; set; }
}

public sealed class ERDTable
{
    [JsonPropertyName("name")]
    public string Name { get; set; } = "";

    [JsonPropertyName("columns")]
    public List<ERDColumn> Columns { get; set; } = [];

    [JsonPropertyName("x")]
    public double X { get; set; } = 100;

    [JsonPropertyName("y")]
    public double Y { get; set; } = 100;
}

public sealed class ERDRelationship
{
    [JsonPropertyName("fromTable")]
    public string FromTable { get; set; } = "";

    [JsonPropertyName("fromColumn")]
    public string FromColumn { get; set; } = "";

    [JsonPropertyName("toTable")]
    public string ToTable { get; set; } = "";

    [JsonPropertyName("toColumn")]
    public string ToColumn { get; set; } = "";

    [JsonPropertyName("kind")]
    public string Kind { get; set; } = "1:N";
}

public sealed class ERDSchema
{
    [JsonPropertyName("tables")]
    public List<ERDTable> Tables { get; set; } = [];

    [JsonPropertyName("relationships")]
    public List<ERDRelationship> Relationships { get; set; } = [];
}

public static class ERDSchemaGenerator
{
    public static string GeneratePostgresSql(ERDSchema schema)
    {
        var sb = new StringBuilder();
        sb.AppendLine("-- PostgreSQL Relational Database Schema DDL");
        sb.AppendLine("-- Generated by KiteWin ERD Schema Studio (Antigravity Standard)");
        sb.AppendLine("CREATE EXTENSION IF NOT EXISTS \"uuid-ossp\";");
        sb.AppendLine();

        foreach (var t in schema.Tables)
        {
            sb.AppendLine($"CREATE TABLE IF NOT EXISTS {t.Name} (");
            var colDefs = new List<string>();

            foreach (var col in t.Columns)
            {
                var def = $"    {col.Name} {col.Type}";
                if (col.IsPrimaryKey) def += " PRIMARY KEY";
                else if (!col.IsNullable) def += " NOT NULL";
                colDefs.Add(def);
            }

            foreach (var rel in schema.Relationships.Where(r => r.FromTable == t.Name))
            {
                var fkName = $"fk_{t.Name}_{rel.FromColumn}";
                colDefs.Add($"    CONSTRAINT {fkName} FOREIGN KEY ({rel.FromColumn}) REFERENCES {rel.ToTable}({rel.ToColumn}) ON DELETE CASCADE");
            }

            sb.AppendLine(string.Join(",\n", colDefs));
            sb.AppendLine(");");
            sb.AppendLine();
        }

        return sb.ToString().TrimEnd();
    }

    public static string GeneratePrismaSchema(ERDSchema schema)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Prisma Data Modeling Schema");
        sb.AppendLine("// Generated by KiteWin ERD Schema Studio");
        sb.AppendLine("datasource db {");
        sb.AppendLine("  provider = \"postgresql\"");
        sb.AppendLine("  url      = env(\"DATABASE_URL\")");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("generator client {");
        sb.AppendLine("  provider = \"prisma-client-js\"");
        sb.AppendLine("}");
        sb.AppendLine();

        foreach (var t in schema.Tables)
        {
            var modelName = char.ToUpperInvariant(t.Name[0]) + t.Name.Substring(1);
            sb.AppendLine($"model {modelName} {{");
            foreach (var col in t.Columns)
            {
                var upper = col.Type.ToUpperInvariant();
                string pType = upper switch
                {
                    var s when s.Contains("UUID") => "String",
                    var s when s.Contains("VARCHAR") || s.Contains("TEXT") => "String",
                    var s when s.Contains("INT") => "Int",
                    var s when s.Contains("BOOL") => "Boolean",
                    var s when s.Contains("TIME") || s.Contains("DATE") => "DateTime",
                    _ => "String"
                };

                var line = $"  {col.Name} {pType}";
                if (col.IsPrimaryKey) line += " @id @default(uuid())";
                sb.AppendLine(line);
            }
            sb.AppendLine($"  @@map(\"{t.Name}\")");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        return sb.ToString().TrimEnd();
    }
}
